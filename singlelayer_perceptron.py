app = FastAPI()

class InputData(BaseModel):
    x1: float
    x2: float

@app.get("/")
def home():
    return {"message": "Perceptron API is running!"}

@app.post("/predict")
def predict(data: InputData):
    prediction = model.predict(
        scaler.transform([[data.x1, data.x2]]),
        verbose=0
    )[0][0]
    return {
        "prediction": int(prediction >= 0.5),
        "probability": float(prediction)
    }

